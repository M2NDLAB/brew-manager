#!/usr/bin/env node
// agent-git-guard — PreToolUse hook for the Bash, PowerShell and Monitor tools, with two
// jobs (docs/04, "Enforcement of the execution boundary").
//
// WHAT. (1) When the hook input carries `agent_id` — the call comes from a delegated agent:
// a subagent or a workflow agent — every git command in it must be a read (docs/04,
// "Delegated agents and the shared working tree"). (2) In every session that runs the
// project's hooks, the main one included, it refuses the git forms that take a hook out —
// its options and configuration; never to get past it, the core's Boundary — and the ones
// an allow rule would let run with no prompt and, in auto mode,
// past the classifier: a file written or read past the repository, an ignored file
// staged, a commit already pushed amended, a branch forced, renamed or deleted with force
// (docs/04, "Permission configuration"). The main session carries no `agent_id` and meets
// job (2) only: docs/04 gives it the local branch work.
// WHY. Agents told "read-only" in their prompt still ran checkout/switch/archive in the
// shared working tree: a sentence in a prompt is not a boundary, this hook is. A linked
// worktree is no exception: it shares refs, config, stash and objects with the repo. And a
// Bash rule matches the command's text: in auto mode Claude Code resolves an allow rule
// before its classifier, so "a narrow rule can still let a destructive argument through
// without the classifier seeing it, for example a script path or flag the rule's prefix
// didn't anticipate" (its Configure auto mode page, read on 2026-10-17), while a hook that
// exits 2 "stops the tool call before permission rules are evaluated" (its Configure
// permissions page).
// SCOPE — the threat model of docs/04 ("Enforcement of the execution boundary"): an
// agent's ACCIDENTAL errors with ordinary commands. The command is read the way the
// agent wrote it: split on shell operators, git — and tree, for job (2) — found after
// leading assignments, shell keywords, a few wrapper commands and git's own global options
// (-C, -c, --git-dir, ...). The PowerShell tool's commands are read the same way, in
// PowerShell's syntax — its backtick escape, script blocks, assignments, here-strings,
// block comments; the framework keeps that tool off (settings.json), and the guard still
// reads it for a developer who turns it on. Whatever the spelling —
// `/usr/bin/git`, `C:\Program Files\Git\cmd\git.exe`, `Git` — git is git: Windows and macOS
// find commands without regard to case. It does NOT look inside `sh -c`, `eval`, scripts
// or interpreter code, nor behind a wrapper it does not list (`sudo`, `find -exec`); nor
// does it see git in an unquoted heredoc's `$(…)` or backticks, after a `case` pattern's
// `)` inside a double-quoted `$(…)`, in a function declared with `function` and no
// parentheses, in a `coproc`, or as a command name held in a variable, nor resolve an
// alias. Its coverage is the forms its self-test holds; docs/04
// lists the rest as outside this layer. A new way past it through the shell's quoting is
// declared there, in the row's Outside column, a LOW, not a defect to chase — unless Claude
// Code itself normally writes the form, as its commit with a heredoc: the guard is one
// defence more, not a sandbox; the deny rules, the pre-push, gitleaks, the classifier and the
// human who publishes remain (the user's rule after the gate's round 2, 2026-10-18). Of them, a
// form that takes the pre-commit out under the shipped `Bash(git commit:*)` leaves gitleaks out
// and, in auto mode, the classifier: there the human who publishes remains (its round 3).
// Pushes themselves are not its job: the pre-push
// hook generated by scripts/hooks-install.sh refuses every push launched from an agent
// session, and job (2) keeps that hook in.
// CONTRACT. stdin: the hook JSON. It reads command text only, but for `git commit --amend`
// and a `git diff` with two paths, for which it runs git's read-only plumbing in the
// repository the command runs in (amendReason, implicitNoIndexReason). Exit 0: no objection
// (the permission flow goes on).
// Exit 2: blocked, the reason on stderr (the agent reads it). Exit 3: unreadable input — a
// FAILURE, not a verdict. .claude/settings.json lets a verdict (0 or 2) stand and turns
// any failure — exit 3, a crash, a missing file, a missing `node` — into a block when the
// input carries the agent_id key (fail-closed for delegated agents) and, otherwise, into
// a non-blocking error (exit 1) that the transcript shows: a broken guard must not cost the
// main session its Bash tool, so job (2)'s forms then rest on the core's rule and on the
// permission mode — but its failure must not go unnoticed.
// Self-test: scripts/test-agent-git-guard.sh.
