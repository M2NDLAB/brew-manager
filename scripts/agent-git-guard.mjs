// The directory a command runs in, as far as its text tells: the hook's `cwd`, moved by
// each earlier `cd` or `pushd` whose one argument is a plain path — a `cd` inside a subshell
// followed as if it lasted —, then by git's own `-C`. null when the text cannot tell: a
// variable, a substitution, a glob, `-`, no argument or `popd`; on Windows a path of Git
// Bash's other than a drive's (`/c/…`).
const MOVES = ['cd', 'pushd', 'chdir', 'sl', 'set-location', 'push-location'];
const UNPLACES = ['popd', 'pop-location'];
function resolveFrom(dir, target) {
  if (dir === null || target === '-' || /[$`*?[\]{}\0]/.test(target)) return null;
  let t = target;
  if (t === '~' || t.startsWith('~/')) t = path.join(os.homedir(), t.slice(1));
  else if (t.startsWith('~')) return null; // another user's home
  if (process.platform === 'win32' && t.startsWith('/')) {
    if (!/^\/[A-Za-z](\/|$)/.test(t)) return null;
    t = `${t[1]}:/${t.slice(3)}`;
  }
  return path.resolve(dir, t);
}
function directoryAfter(words, dir, powershell) {
  if (UNPLACES.some((name) => findCommand(words, name, powershell))) return null;
  for (const name of MOVES) {
    const found = findCommand(words, name, powershell);
    if (!found) continue;
    // cd's own options (-L, -P, -e, -@, --) and PowerShell's -Path / -LiteralPath name no place
    const places = found.args.filter((word) => !/^(?:-[LPe@]+|--|-(?:literal)?path)$/i.test(word));
    return places.length === 1 ? resolveFrom(dir, places[0]) : null;
  }
  return dir;
}

// Where a git invocation reads its repository: the directory, and the options and variables
// that choose another (`--git-dir`, `--work-tree`, GIT_DIR, GIT_WORK_TREE, GIT_COMMON_DIR);
// null when the text cannot tell.
function gitLocation(globals, assignments, dir) {
  const location = { cwd: dir, options: [], env: {} };
  for (let k = 0; k < globals.length; k += 1) {
    const flag = globals[k].split('=')[0];
    const glued = globals[k].includes('=');
    if (globals[k] === '-C') { location.cwd = resolveFrom(location.cwd, globals[k + 1] ?? ''); k += 1; continue; }
    if (flag === '--git-dir' || flag === '--work-tree') {
      const value = glued ? globals[k].slice(flag.length + 1) : globals[k + 1];
      if (!glued) k += 1;
      if (value === undefined || /[$`\0]/.test(value)) return null;
      location.options.push(`${flag}=${value}`);
      continue;
    }
    if (GIT_OPTIONS_WITH_VALUE.has(globals[k])) k += 1;
  }
  for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR']) {
    if (assignments[name] === undefined) continue;
    if (/[$`\0]/.test(assignments[name])) return null;
    location.env[name] = assignments[name];
  }
  return location.cwd === null ? null : location;
}

// A read of git's plumbing where `location` says: rev-parse and rev-list, which run no hook
// and no configured program; the optional locks off, a 5-second timeout, no shell. Its
// output, or why it failed — git's own first line —, which the refusal then quotes.
function gitRead(location, args) {
  try {
    const out = execFileSync('git', [...location.options, ...args], {
      cwd: location.cwd, encoding: 'utf8', timeout: 5000, windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, ...location.env, GIT_OPTIONAL_LOCKS: '0' },
    });
    return { ok: true, out: out.trim() };
  } catch (error) {
    const detail = `${error.stderr ?? ''}`.trim().split('\n')[0] || error.message.split('\n')[0];
    return { ok: false, detail };
  }
}

// Why amending HEAD where `location` says is refused, or null. A commit its upstream already
// holds — or a remote-tracking branch: a branch pushed without -u, a new branch still on the
// integration branch's pushed tip — is shared history, and amending it rewrites what the
// remote has. The shipped `Bash(git commit:*)` resolves before auto mode's classifier, whose
// rule on amending a pushed commit then never sees the call (the gate's round 1,
// 2026-10-18). Only a positive datum lets it through: git read the repository, and HEAD is
// in neither; a local commit's amend stays the main session's.
function amendReason(location) {
  const unknown = (why) => `\`git commit --amend\`: the guard cannot tell whether HEAD is already pushed (${why})`;
  if (location === null) return unknown('the text does not say which repository it runs in');
  const head = gitRead(location, ['rev-parse', '--verify', '-q', 'HEAD']);
  if (!head.ok) return unknown(head.detail || 'no commit at HEAD');
  const upstream = gitRead(location, ['rev-parse', '--symbolic-full-name', '@{upstream}']);
  const own = gitRead(location, ['rev-list', '-n', '1', 'HEAD', '--not', '--remotes',
    ...(upstream.ok && upstream.out ? [upstream.out] : [])]);
  if (!own.ok) return unknown(own.detail);
  return own.out === '' ? '`git commit --amend` rewrites a commit its upstream or a remote-tracking branch already holds' : null;
}

// A path with its symbolic links resolved, as far as it exists: a part that does not exist yet
// keeps its name under its parent's real path (`/tmp/x` on macOS is `/private/tmp/x`).
function realPath(p) {
  try {
    return realpathSync.native(p);
  } catch {
    const parent = path.dirname(p);
    return parent === p ? p : path.join(realPath(parent), path.basename(p));
  }
}
// Whether `p` is inside the directory `root` — without regard to case where the filesystem's
// default has none (macOS, Windows), as git compares there.
function insideOf(root, p) {
  const fold = (s) => (['darwin', 'win32'].includes(process.platform) ? s.toLowerCase() : s);
  const r = fold(realPath(root)); const q = fold(realPath(p));
  return q === r || q.startsWith(r.endsWith(path.sep) ? r : r + path.sep);
}

// Whether a path is written as one outside any work tree: absolute — `/…`, `\…`, `C:\…` —, from
// a home directory, `~…`, or climbing with a `..`.
const writtenOutside = (word) => /^(?:[\\/~]|[A-Za-z]:[\\/])/.test(word) || /(?:^|[\\/])\.\.(?:[\\/]|$)/.test(word);
// Why this `git diff` compares two files as `--no-index` does without saying so, or null. git
// 2.54.0's own rule (builtin/diff.c): outside a repository it always does; inside one, when
// exactly two words follow its leading options — and an optional `--` — and either is outside
// the work tree (path_inside_repo). Its loop does not skip an option's value: `-S x a b` is
// three words there, not two. Measured on 2026-10-18: an ignored file against /dev/null, and
// a file outside the work tree, printed their lines. Where git finds no work tree, two
// operands are refused; where the text cannot tell where it runs, below.
function implicitNoIndexReason(rest, location) {
  let i = 0;
  for (; i < rest.length; i += 1) {
    if (rest[i] === '--') { i += 1; break; }
    if (!rest[i].startsWith('-')) break;
  }
  const words = rest.slice(i);
  const operands = words.length === 2 ? words : readOptions(rest, DIFFS).operands;
  if (operands.length !== 2) return null;
  const reason = '`git diff <path> <path>` compares two files as `--no-index` does when one is outside the work tree, or outside a repository';
  // Where the text does not say which directory it runs in — a variable, a substitution, as in
  // the upgrade's `git -C "${FW:?}" diff vX vY` —, the operands alone decide: one written as a
  // path outside any work tree, or one the text cannot read, is refused; two revisions or
  // relative names pass — the guard refused them all once, the method's own form among them
  // (the rehearsal, 2026-10-18) —, a comparison of two files where no repository is left
  // outside this check (docs/04 declares it).
  if (location === null) {
    return operands.some((word) => writtenOutside(word) || /[$`\0]/.test(word))
      ? `${reason} (the guard cannot tell where it runs, and an operand is written as a path outside or holds what the text cannot read)` : null;
  }
  const top = gitRead(location, ['rev-parse', '--show-toplevel']);
  if (!top.ok) return reason; // no work tree there: git compares any two paths
  if (words.length !== 2) return null;
  // An operand the guard cannot place — a variable, a substitution, a glob, a brace, `@{u}`
  // among them — is refused as one outside: the gate's round 2 found the message claiming a
  // path outside for `git diff @{u} HEAD`; the range in one operand, `@{u}..HEAD`, passes.
  const places = words.map((word) => resolveFrom(location.cwd, word));
  if (places.includes(null)) return `${reason} (an operand the guard cannot place: a variable, a substitution, a glob or a brace; a range in one operand, A..B, passes)`;
  return places.some((where) => !insideOf(top.out, where)) ? reason : null;
}

// Why this git invocation is refused in every session, or null; `dir` is where it runs
// (directoryAfter), for the amend's check.
function gitEverySessionReason({ args, assignments }, dir) {
  const { globals, sub, rest } = gitParts(args);
  // `-c core.hooksPath=…`, `--config-env`, or GIT_CONFIG_KEY_<n> and GIT_CONFIG_PARAMETERS in
  // the assignments before git: for that command git reads its hooks from elsewhere. An
  // earlier `export` of them is not read (docs/04 declares it).
  if ([...globals, ...Object.values(assignments)].some(hooksPath)) return '`core.hooksPath` set for one command takes its hooks out';
  if (sub === undefined) return null;
  const { letters: short, longs } = readOptions(rest, VALUED[sub]);
  const long = (name) => longs.some((word) => spells(word, name));
  if (VERIFYING.has(sub) && long('--no-verify')) return `\`git ${sub} --no-verify\` takes a hook out`;
  if (sub === 'commit' && short.has('n')) return '`git commit -n` takes the pre-commit and commit-msg hooks out';
  if (sub === 'commit' && long('--amend')) {
    const pushed = amendReason(gitLocation(globals, assignments, dir));
    if (pushed) return pushed;
  }
  // Setting it — not reading or unsetting it: an unset gives git back its own hooks directory.
  if (sub === 'config' && rest.some(hooksPath) && !READ_FORMS.config(rest)
    && !rest.some((word) => ['--unset', '--unset-all', 'unset'].includes(word))) return '`git config core.hooksPath` takes the hooks out';
  // `git stage` is git-add(1)'s synonym. An ignored file staged is a secret's way into a
  // commit (the core's rule 1), past the refusal a plain `git add` gives it.
  if ((sub === 'add' || sub === 'stage') && (short.has('f') || long('--force'))) {
    return `\`git ${sub} -f\` stages a file .gitignore leaves out`;
  }
  if (OUTPUT.has(sub) && long('--output')) return `\`git ${sub} --output\` writes a file`;
  if (sub === 'diff' && long('--no-index')) return '`git diff --no-index` reads files past the repository';
  if (sub === 'diff') {
    const read = implicitNoIndexReason(rest, gitLocation(globals, assignments, dir));
    if (read) return read;
  }
  if (sub === 'branch') {
    const force = short.has('f') || long('--force');
    if (short.has('D') || (force && (short.has('d') || long('--delete')))) return '`git branch -D` deletes a branch that may hold unmerged work';
    if (force) return '`git branch -f` moves a branch away from its commits';
    if (short.has('m') || short.has('M') || long('--move')) return '`git branch -m` renames a branch';
    if (short.has('C')) return '`git branch -C` copies over an existing branch';
  }
  return null;
}
// Why this tree invocation is refused in every session, or null. tree reads each letter of
// a cluster as an option (measured: `tree -ao <file>` wrote) and no prefix of a long one
// (`--fromf` is refused): a prefix refused here costs nothing. `--fromfile` reads the paths
// it is given as files, and `.` — its default — as stdin: refused with a path only, so
// `git ls-files | tree --fromfile`, TREE.md's fallback, passes.
function treeReason(args) {
  const { letters, longs, operands } = readOptions(args, TREE_VALUED);
  if (letters.has('o')) return '`tree -o` writes a file';
  if (letters.has('R')) return '`tree -R` writes a file in each directory it reaches';
  // measured on tree 2.3.2: the file's lines open, or close, the `-H` output
  if (longs.some((word) => spells(word, '--hintro') || spells(word, '--houtro'))) return '`tree --hintro` prints the file it is given';
  if (longs.some((word) => spells(word, '--fromfile') || spells(word, '--fromtabfile'))
    && operands.some((word) => word !== '.')) return '`tree --fromfile <path>` prints the lines of the file it reads';
  return null;
}
// Job (2) for one simple command, run in `dir`.
function everySessionReason(words, powershell, dir) {
  const git = findGit(words, powershell);
  if (git) return gitEverySessionReason(git, dir);
  const tree = findCommand(words, 'tree', powershell);
  return tree ? treeReason(tree.args) : null;
}

// Why this git invocation writes, or null when it only reads (job 1).
function writeReason({ args, assignments }) {
  const { globals, sub, rest } = gitParts(args);
  if (sub === undefined) return null; // `git --version`, `git -C dir` alone
  if (readOptions(rest, VALUED[sub]).longs.some((word) => word.split('=')[0] === '--output')) return `\`git ${sub} --output\` writes a file`;
  if (sub === 'status') {
    const quiet = globals.includes('--no-optional-locks') || assignments.GIT_OPTIONAL_LOCKS === '0';
    // A plain status refreshes and rewrites .git/index, and its lock can make a concurrent git
    // command fail. Other reads can refresh the index too (`git diff` on a stale stat cache):
    // only status, the common case, is singled out.
    return quiet ? null : 'a plain `git status` rewrites .git/index: use `git --no-optional-locks status`';
  }
  if (READ_ONLY.has(sub)) return null;
  if (READ_FORMS[sub] && READ_FORMS[sub](rest)) return null;
  return `\`git ${sub}\` can write repository state`;
}

